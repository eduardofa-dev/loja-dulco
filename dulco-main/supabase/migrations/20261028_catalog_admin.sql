  (2, 'Bolo de Pote', 'Um momento doce para aproveitar de colher.', 15, '/imagens/bolonopote.png', 'Bolos de pote', 2, true),
  (3, 'Bombom de Brownie', 'Brownie em uma versão para saborear a cada mordida.', 6, '/imagens/bombombrownie.png', 'Brownies', 3, false),
  (4, 'Morango do Amor', 'Uma escolha especial para quem ama morango.', 28, '/imagens/morangodoamor.png', 'Doces especiais', 4, false),
  (5, 'Bora com Chocolate', 'Uma opção deliciosa para a hora da sobremesa.', 28, '/imagens/boracomchocolate.png', 'Doces especiais', 5, false),
  (6, 'Bombom no Pote de Morango', 'Uma combinação em pote para fãs de morango.', 28, '/imagens/potemorango.png', 'Bolos de pote', 6, false),
  (7, 'Bombom no Pote de Uva', 'Um docinho de pote para quem ama uva.', 28, '/imagens/poteuva.png', 'Bolos de pote', 7, false),
