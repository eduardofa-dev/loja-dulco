-- Executar no SQL Editor do Supabase antes de usar /admin.
-- A função de administrador é protegida no banco de dados; nunca use service_role no browser.
begin;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
revoke all on public.admin_users from anon;
grant select on public.admin_users to authenticated;

drop policy if exists "Admin can read own membership" on public.admin_users;
create policy "Admin can read own membership" on public.admin_users
  for select to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.is_admin()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 120),
  description text not null default '' check (char_length(description) <= 500),
  price numeric(10,2) not null check (price > 0 and price <= 99999.99),
  image_url text not null default '' check (char_length(image_url) <= 2048),
  category text not null default 'Doces especiais' check (char_length(trim(category)) between 1 and 60),
  is_available boolean not null default true,
  is_visible boolean not null default true,
  is_featured boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products enable row level security;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

drop policy if exists "Catalog visible to visitors" on public.products;
create policy "Catalog visible to visitors" on public.products
  for select to anon, authenticated using (is_visible = true);

drop policy if exists "Admin sees all products" on public.products;
create policy "Admin sees all products" on public.products
  for select to authenticated using ((select public.is_admin()));

drop policy if exists "Only admin inserts products" on public.products;
create policy "Only admin inserts products" on public.products
  for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "Only admin updates products" on public.products;
create policy "Only admin updates products" on public.products
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Only admin deletes products" on public.products;
create policy "Only admin deletes products" on public.products
  for delete to authenticated using ((select public.is_admin()));

insert into public.products
